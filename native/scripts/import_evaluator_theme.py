#!/usr/bin/env python3
"""Import original embedded Evaluator themes; rasterize their original SVG symbols.

Usage: python3 import_evaluator_theme.py /path/to/ilspy/project
Requires Linux librsvg and Cairo. This is an asset import tool,
not a runtime dependency. Source SVGs remain next to the generated PNGs.
"""
import base64
import ctypes as ffi
import ctypes.util
import json
import re
from pathlib import Path
import sys
from urllib.parse import unquote

source = Path(sys.argv[1])
output = Path(__file__).resolve().parents[1] / "observatory-desktop/assets/evaluator"
output.mkdir(parents=True, exist_ok=True)
entries = []
rsvg = ffi.CDLL(ctypes.util.find_library("rsvg-2"))
cairo = ffi.CDLL(ctypes.util.find_library("cairo"))
gobject = ffi.CDLL(ctypes.util.find_library("gobject-2.0"))
class Viewport(ffi.Structure):
    _fields_ = [(key, ffi.c_double) for key in ["x", "y", "width", "height"]]
rsvg.rsvg_handle_new_from_data.argtypes = [ffi.c_char_p, ffi.c_size_t, ffi.c_void_p]
rsvg.rsvg_handle_new_from_data.restype = ffi.c_void_p
rsvg.rsvg_handle_render_document.argtypes = [ffi.c_void_p, ffi.c_void_p, ffi.POINTER(Viewport), ffi.c_void_p]
rsvg.rsvg_handle_render_document.restype = ffi.c_int
cairo.cairo_image_surface_create.argtypes = [ffi.c_int, ffi.c_int, ffi.c_int]
cairo.cairo_image_surface_create.restype = ffi.c_void_p
cairo.cairo_create.argtypes = [ffi.c_void_p]
cairo.cairo_create.restype = ffi.c_void_p
cairo.cairo_surface_write_to_png.argtypes = [ffi.c_void_p, ffi.c_char_p]
cairo.cairo_destroy.argtypes = [ffi.c_void_p]
cairo.cairo_surface_destroy.argtypes = [ffi.c_void_p]
gobject.g_object_unref.argtypes = [ffi.c_void_p]
def rasterize(path, size):
    svg = path.read_bytes()
    handle = rsvg.rsvg_handle_new_from_data(svg, len(svg), None)
    if not handle:
        raise ValueError(f"Invalid original SVG: {path.name}")
    surface = cairo.cairo_image_surface_create(0, size, size)
    context = cairo.cairo_create(surface)
    viewport = Viewport(0, 0, size, size)
    if not rsvg.rsvg_handle_render_document(handle, context, ffi.byref(viewport), None):
        raise ValueError(f"SVG rendering failed: {path.name}")
    if cairo.cairo_surface_write_to_png(surface, str(path.with_suffix(".png")).encode()) != 0:
        raise ValueError(f"PNG export failed: {path.name}")
    cairo.cairo_destroy(context)
    cairo.cairo_surface_destroy(surface)
    gobject.g_object_unref(handle)
for theme in ["theme", "theme-orange"]:
    resource = source / f"Evaluator.Resources.{theme}.json"
    data = json.loads(resource.read_text(encoding="utf-8-sig"))
    (output / f"{theme}.json").write_text(json.dumps(data, indent=2) + "\n")
    for key, symbol in data["Symbols"].items():
        if symbol.get("ContentType") != "Base64SVG":
            continue
        color = symbol.get("ContentColor", data["Colors"].get(
            symbol.get("ContentColorKey", "DefaultText"), {"R": 255, "G": 255, "B": 255}))
        rgb = "".join(format(color[c], "02x") for c in ["R", "G", "B"])
        svg = base64.b64decode(symbol["Content"]).decode().replace("$$COLOR$$", rgb)
        path = output / f"{theme}-{key}.svg"
        path.write_text(svg)
        rasterize(path, 24)
        entries.append((theme, key, path.with_suffix(".png").name))
    buttons = (source / "Evaluator.Resources.buttons.css").read_text(encoding="utf-8-sig")
    for key, encoded in re.findall(r'\.buttonheader #([\w-]+)\s*\{\s*background-image:\s*url\("data:image/svg\+xml,([^\"]+)"\)', buttons):
        color = data["Colors"]["Button"]
        rgb = "".join(format(color[c], "02x") for c in ["R", "G", "B"])
        svg = unquote(encoded).replace("$$BUTTON$$", rgb)
        path = output / f"{theme}-Button-{key}.svg"
        path.write_text(svg)
        rasterize(path, 32)
        entries.append((theme, f"Button-{key}", path.with_suffix(".png").name))
    for key, encoded in re.findall(r'\.buttonheader #([\w-]+)\s*\{\s*background-image:\s*url\("data:image/png;base64,([^\"]+)"\)', buttons):
        path = output / f"{theme}-Button-{key}.png"
        path.write_bytes(base64.b64decode(encoded))
        entries.append((theme, f"Button-{key}", path.name))
rust = ['// Generated by scripts/import_evaluator_theme.py from original embedded SVGs.',
        'pub fn symbol(orange: bool, key: &str) -> Option<(&\'static str, &\'static [u8])> {',
        '    match (orange, key) {']
for theme, key, filename in entries:
    rust.append(f'        ({str(theme == "theme-orange").lower()}, "{key}") => Some(("{filename}", include_bytes!("../assets/evaluator/{filename}"))),')
rust += ['        _ => None,', '    }', '}']
(output.parents[1] / "src/evaluator_symbols.rs").write_text("\n".join(rust) + "\n")
print(f"Imported {len(entries)} original Evaluator symbols in both themes")
