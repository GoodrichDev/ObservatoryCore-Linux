//! Spansh dump conversion used by Hecate's SpanshSystem response.
use super::storage::{epoch, now, timestamp};
use anyhow::{Context, Result};
use serde_json::{json, Value};
use std::{
    collections::{HashMap, HashSet},
    sync::OnceLock,
};

fn identifiers() -> &'static Value {
    static TABLES: OnceLock<Value> = OnceLock::new();
    TABLES.get_or_init(|| {
        serde_json::from_str(include_str!("identifiers.json")).expect("embedded Hecate identifiers")
    })
}
fn name(table: &str, id: &str) -> String {
    identifiers()[table][id].as_str().unwrap_or("").to_owned()
}
fn id(table: &str, name: &str) -> String {
    identifiers()[format!("{table}_by_name")][name]
        .as_str()
        .map(str::to_owned)
        .unwrap_or_else(|| {
            identifiers()[table]
                .as_object()
                .and_then(|table| table.iter().find(|(_, value)| value.as_str() == Some(name)))
                .map(|(key, _)| key.clone())
                .unwrap_or_default()
        })
}
fn s<'a>(value: &'a Value, key: &str) -> &'a str {
    value[key].as_str().unwrap_or("")
}
fn n(value: &Value, key: &str) -> f64 {
    value
        .get(key)
        .or_else(|| {
            value.as_object().and_then(|map| {
                map.iter()
                    .find(|(name, _)| name.eq_ignore_ascii_case(key))
                    .map(|(_, value)| value)
            })
        })
        .and_then(Value::as_f64)
        .unwrap_or(0.)
}
fn array(value: &Value) -> &[Value] {
    value.as_array().map(Vec::as_slice).unwrap_or(&[])
}
fn scaled(value: &Value, key: &str, factor: f32) -> Value {
    // Vendor properties use Single and JSON's shortest round-trip decimal.
    serde_json::from_str(&(n(value, key) as f32 * factor).to_string()).unwrap_or(Value::Null)
}

/// Recreate the journal sequence generated by the installed Hecate converter.
/// Input may be either the dump root (`system`) or a system object.
pub fn from_spansh(dump: &Value, visit_date: Option<&str>) -> Result<Vec<Value>> {
    let system = dump.get("system").unwrap_or(dump);
    let address = system
        .get("id64")
        .or_else(|| system.get("id"))
        .and_then(Value::as_u64)
        .context("Spansh system has no unsigned id64")?;
    let system_name = s(system, "name");
    let mut bodies: Vec<&Value> = array(&system["bodies"]).iter().collect();
    bodies.sort_by_key(|body| body["bodyId"].as_i64().unwrap_or(0));
    if bodies.is_empty() {
        return Ok(Vec::new());
    }
    let seed = epoch(visit_date.unwrap_or(&now()))?;
    let mut counter = 0;
    let mut stamp = |mut event: Value| {
        event["timestamp"] = json!(timestamp(seed + counter));
        counter += 1;
        event
    };
    let first = bodies[0];
    let mut events = vec![stamp(
        json!({"event":"Location","DistFromStarLS":n(first,"distanceToArrival"),"Docked":false,"Taxi":false,"Multicrew":false,"StarSystem":system_name,"SystemAddress":address,"StarPos":[n(&system["coords"],"x"),n(&system["coords"],"y"),n(&system["coords"],"z")],"SystemAllegiance":id("systemallegiance",s(system,"allegiance")),"SystemEconomy":id("economy",s(system,"primaryEconomy")),"SystemEconomy_Localised":s(system,"primaryEconomy"),"SystemSecondEconomy":id("economy",s(system,"secondaryEconomy")),"SystemSecondEconomy_Localised":s(system,"secondaryEconomy"),"SystemGovernment":id("government",s(system,"government")),"SystemGovernment_Localised":s(system,"government"),"SystemSecurity":id("security",s(system,"security")),"SystemSecurity_Localised":s(system,"security"),"Population":system["population"].as_i64().unwrap_or(0),"Body":s(first,"name"),"BodyID":first["bodyId"].as_i64().unwrap_or(0),"BodyType":s(first,"type")}),
    )];
    let body_count = system["bodyCount"].as_i64().unwrap_or_else(|| {
        bodies
            .iter()
            .filter(|body| s(body, "type") != "Barycentre")
            .count() as i64
    });
    events.push(stamp(json!({"event":"FSSDiscoveryScan","Progress":100.,"BodyCount":body_count,"NonBodyCount":bodies.len()as i64-body_count,"SystemName":system_name,"SystemAddress":address})));
    let barycentres: HashMap<i64, &Value> = bodies
        .iter()
        .filter(|body| s(body, "type") == "Barycentre")
        .map(|body| (body["bodyId"].as_i64().unwrap_or(0), *body))
        .collect();
    let mut included = HashSet::new();
    let mut mapping_events = Vec::new();
    for kind in ["Star", "Planet"] {
        for body in bodies.iter().filter(|body| s(body, "type") == kind) {
            if kind == "Star" {
                add_barycentres(
                    &mut events,
                    &barycentres,
                    &mut included,
                    body,
                    system_name,
                    address,
                    &mut stamp,
                );
            }
            let mut scan = json!({"event":"Scan","ScanType":if kind=="Star"{"AutoScan"}else{"Detailed"},"BodyName":s(body,"name"),"BodyID":body["bodyId"].as_i64().unwrap_or(0),"Parents":body.get("parents").cloned().unwrap_or(json!([])),"StarSystem":system_name,"SystemAddress":address,"DistanceFromArrivalLS":n(body,"distanceToArrival"),"WasDiscovered":true,"WasMapped":kind=="Planet","Rings":rings(body)});
            orbit(&mut scan, body);
            scan["RotationPeriod"] = scaled(body, "rotationalPeriod", 86400.);
            scan["AxialTilt"] = json!(n(body, "axialTilt"));
            scan["SurfaceTemperature"] = json!(n(body, "surfaceTemperature"));
            if kind == "Star" {
                scan["StarType"] = json!(id("bodies", s(body, "subType")));
                scan["Subclass"] = json!(s(body, "spectralClass")
                    .chars()
                    .find_map(|c| c.to_digit(10))
                    .map(i64::from)
                    .unwrap_or(-1));
                scan["StellarMass"] = json!(n(body, "solarMasses"));
                scan["Radius"] = scaled(body, "solarRadius", 695500000.);
                scan["AbsoluteMagnitude"] = json!(n(body, "absoluteMagnitude"));
                scan["Age_MY"] = json!(n(body, "age"));
                scan["Luminosity"] = json!(s(body, "luminosity"));
            } else {
                let atmosphere = s(body, "atmosphereType").to_lowercase();
                let volcanism = s(body, "volcanismType").to_lowercase();
                scan["TidalLock"] = json!(body["rotationalPeriodTidallyLocked"]
                    .as_bool()
                    .unwrap_or(false));
                scan["TerraformState"] = json!(s(body, "terraformingState"));
                scan["PlanetClass"] = json!(id("bodies", s(body, "subType")));
                scan["Atmosphere"] = json!(if atmosphere.is_empty() || atmosphere == "none" {
                    String::new()
                } else {
                    format!("{atmosphere} atmosphere")
                });
                scan["AtmosphereType"] = json!(atmosphere_type(&atmosphere));
                scan["AtmosphereComposition"] = composition(&body["atmosphereComposition"], false);
                scan["Volcanism"] = json!(if volcanism.is_empty() {
                    String::new()
                } else {
                    format!("{volcanism} volcanism")
                });
                scan["MassEM"] = json!(n(body, "earthMasses"));
                scan["Radius"] = scaled(body, "radius", 1000.);
                scan["SurfaceGravity"] = scaled(body, "gravity", 9.81);
                scan["SurfacePressure"] = scaled(body, "surfacePressure", 101325.);
                scan["Landable"] = json!(
                    !atmosphere.is_empty()
                        && ((atmosphere.contains("thin ") && n(body, "surfacePressure") < 0.1)
                            || body["isLandable"].as_bool().unwrap_or(false))
                );
                scan["Materials"] = composition(&body["materials"], true);
                scan["Composition"] = if body["solidComposition"].is_null() {
                    Value::Null
                } else {
                    json!({"Ice":n(&body["solidComposition"],"ice")/100.,"Rock":n(&body["solidComposition"],"rock")/100.,"Metal":n(&body["solidComposition"],"metal")/100.})
                };
            }
            if kind == "Planet" {
                let signals = convert_signals(&body["signals"]["signals"], false);
                if !signals.is_empty() {
                    let base = json!({"BodyName":s(body,"name"),"BodyID":body["bodyId"].as_i64().unwrap_or(0),"SystemAddress":address});
                    let mut fss = base.clone();
                    fss["event"] = json!("FSSBodySignals");
                    fss["Signals"] = json!(signals);
                    events.push(stamp(fss));
                    if !array(&body["signals"]["genuses"]).is_empty() {
                        let mut saa = base.clone();
                        saa["event"] = json!("SAAScanComplete");
                        mapping_events.push(stamp(saa));
                        let mut found = base;
                        found["event"] = json!("SAASignalsFound");
                        found["Signals"] = json!(signals);
                        found["Genuses"]=json!(array(&body["signals"]["genuses"]).iter().filter_map(|genus|genus.as_str()).map(|genus|json!({"Genus":if genus.starts_with('$'){genus.to_owned()}else{id("genuses",genus)},"Genus_Localised":if genus.starts_with('$'){name("genuses",genus)}else{genus.to_owned()}})).collect::<Vec<_>>());
                        mapping_events.push(stamp(found));
                    }
                }
                for ring in array(&body["rings"]) {
                    let signals = convert_signals(&ring["signals"]["signals"], true);
                    if signals.is_empty() {
                        continue;
                    }
                    let ring_id = ring["id64"]
                        .as_u64()
                        .map(|id| (id >> 55) as i64)
                        .unwrap_or(0);
                    mapping_events.push(stamp(json!({"event":"SAAScanComplete","BodyName":s(ring,"name"),"BodyID":ring_id,"SystemAddress":address})));
                    mapping_events.push(stamp(json!({"event":"SAASignalsFound","BodyName":s(ring,"name"),"BodyID":ring_id,"SystemAddress":address,"Signals":signals})));
                }
                add_barycentres(
                    &mut events,
                    &barycentres,
                    &mut included,
                    body,
                    system_name,
                    address,
                    &mut stamp,
                );
            }
            events.push(stamp(scan));
        }
    }
    events.push(stamp(json!({"event":"FSSAllBodiesFound","SystemName":system_name,"SystemAddress":address,"Count":body_count})));
    events.extend(mapping_events);
    Ok(events)
}
fn orbit(event: &mut Value, body: &Value) {
    for (to, from, factor) in [
        ("SemiMajorAxis", "semiMajorAxis", 1.4959786e11_f32),
        ("OrbitalPeriod", "orbitalPeriod", 86400.),
        ("Eccentricity", "orbitalEccentricity", 1.),
        ("OrbitalInclination", "orbitalInclination", 1.),
        ("Periapsis", "argOfPeriapsis", 1.),
        ("AscendingNode", "ascendingNode", 1.),
        ("MeanAnomaly", "meanAnomaly", 1.),
    ] {
        event[to] = scaled(body, from, factor);
    }
}
fn add_barycentres(
    events: &mut Vec<Value>,
    centres: &HashMap<i64, &Value>,
    included: &mut HashSet<i64>,
    body: &Value,
    system_name: &str,
    address: u64,
    stamp: &mut impl FnMut(Value) -> Value,
) {
    for parent in array(&body["parents"]).iter().rev() {
        if let Some(id) = parent.get("Null").and_then(Value::as_i64) {
            if included.insert(id) {
                if let Some(centre) = centres.get(&id) {
                    let mut event = json!({"event":"ScanBaryCentre","StarSystem":system_name,"SystemAddress":address,"BodyID":id});
                    orbit(&mut event, centre);
                    events.push(stamp(event));
                }
            }
        }
    }
}
fn atmosphere_type(text: &str) -> String {
    let mut text = text.to_lowercase();
    for prefix in ["hot ", "thin ", "thick "] {
        if let Some(rest) = text.strip_prefix(prefix) {
            text = rest.to_owned();
        }
    }
    text = text.replace("-rich", " rich");
    let name = text
        .split_whitespace()
        .map(|word| {
            let mut chars = word.chars();
            chars
                .next()
                .map(|c| c.to_uppercase().collect::<String>() + chars.as_str())
                .unwrap_or_default()
        })
        .collect::<String>();
    if name == "NoAtmosphere" || name.is_empty() {
        "None".into()
    } else {
        name
    }
}
fn composition(value: &Value, lowercase: bool) -> Value {
    json!(value.as_object().map(|map|map.iter().map(|(name,amount)|json!({"Name":if lowercase{name.to_lowercase()}else{name.clone()},"Percent":amount})).collect::<Vec<_>>()).unwrap_or_default())
}
fn rings(body: &Value) -> Value {
    json!(array(&body["rings"]).iter().map(|ring|json!({"Name":s(ring,"name"),"RingClass":id("rings",s(ring,"type")),"MassMT":n(ring,"mass"),"InnerRad":n(ring,"innerRadius"),"OuterRad":n(ring,"outerRadius")})).collect::<Vec<_>>())
}
fn convert_signals(value: &Value, commodity: bool) -> Vec<Value> {
    let convert = |symbol: &str, count: &Value| {
        let localized = name(
            if commodity {
                "commodity"
            } else {
                "saa_signals"
            },
            symbol,
        );
        if localized.is_empty() && !commodity {
            None
        } else {
            Some(json!({"Type":symbol,"Type_Localised":localized,"Count":count}))
        }
    };
    if let Some(map) = value.as_object() {
        map.iter()
            .filter_map(|(symbol, count)| convert(symbol, count))
            .collect()
    } else {
        array(value)
            .iter()
            .filter_map(|signal| {
                let symbol = s(signal, "name");
                convert(symbol, signal.get("value").unwrap_or(&Value::Null))
            })
            .collect()
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn converts_real_dump_shape_with_original_units_and_identifiers() {
        assert_eq!(id("genuses", "Clypeus"), "$Codex_Ent_Clypeus_Genus_Name;");
        let dump = json!({"system":{"id64":18446744073709551615_u64,"name":"Native","bodyCount":2,"coords":{"x":1,"y":2,"z":3},"bodies":[{"bodyId":0,"type":"Star","subType":"G (White-Yellow) Star","name":"Native","solarRadius":1,"spectralClass":"G2 V"},{"bodyId":2,"type":"Planet","name":"Native 1","subType":"High metal content world","radius":1000,"gravity":1,"surfacePressure":0.01,"atmosphereType":"Thin Carbon dioxide","isLandable":true,"semiMajorAxis":1,"orbitalPeriod":2,"materials":{"Iron":5},"signals":{"signals":{"$SAA_SignalType_Biological;":2},"genuses":["Bacterium","Stratum"]}}]}});
        let events = from_spansh(&dump, Some("2026-10-25T00:00:00Z")).unwrap();
        assert_eq!(events[0]["StarPos"], json!([1., 2., 3.]));
        assert_eq!(events[0]["SystemAddress"], u64::MAX);
        let scans: Vec<_> = events
            .iter()
            .filter(|event| event["event"] == "Scan")
            .collect();
        assert_eq!(scans.len(), 2);
        assert_eq!(scans[0]["StarType"], "G");
        assert_eq!(scans[0]["Subclass"], 2);
        assert_eq!(scans[0]["Radius"], 695500000.);
        assert_eq!(scans[1]["PlanetClass"], "High metal content body");
        assert_eq!(scans[1]["Radius"], 1000000.);
        assert_eq!(scans[1]["OrbitalPeriod"], 172800.);
        assert_eq!(scans[1]["AtmosphereType"], "CarbonDioxide");
        assert_eq!(scans[1]["Landable"], true);
        let found = events
            .iter()
            .find(|event| event["event"] == "SAASignalsFound")
            .unwrap();
        assert_eq!(
            found["Genuses"][0]["Genus"],
            "$Codex_Ent_Bacterial_Genus_Name;"
        );
        assert_eq!(found["Signals"][0]["Count"], 2);
        assert_eq!(
            events
                .iter()
                .filter(|event| event["event"] == "FSSAllBodiesFound")
                .count(),
            1
        );
    }
    #[test]
    fn places_barycentre_before_its_scan_and_maps_ring_hotspots() {
        let body = json!({"id64":1,"name":"Binary","bodies":[{"bodyId":0,"type":"Barycentre","semiMajorAxis":1},{"bodyId":1,"type":"Star","name":"Binary A","parents":[{"Null":0}],"subType":"Neutron Star"},{"bodyId":2,"type":"Planet","name":"Binary A 1","rings":[{"name":"Binary A 1 A Ring","id64":(4_u64<<55),"type":"Icy","signals":{"signals":{"LowTemperatureDiamond":3}}}]}]});
        let events = from_spansh(&body, Some("2026-10-25T00:00:00Z")).unwrap();
        assert_eq!(events[2]["event"], "ScanBaryCentre");
        assert_eq!(events[3]["event"], "Scan");
        assert_eq!(events[3]["StarType"], "N");
        assert!(events
            .iter()
            .any(|event| event["event"] == "SAASignalsFound" && event["BodyID"] == 4));
    }
}
